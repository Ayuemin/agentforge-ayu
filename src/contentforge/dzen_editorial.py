def _strip_markup(text: str) -> str:
    text = re.sub(r"<!--[\s\S]*?-->", "", text)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s+", "", text)
    text = re.sub(r"(?m)^\s*[-*+]\s+", "", text)
    text = re.sub(r"(?m)^\s*\d+\.\s+", "", text)
    text = re.sub(r"(?m)^\s*>\s?", "", text)
    text = re.sub(r"[*_~\x60]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def article_audit(text: str, minimum: int = 4000, maximum: int = 8000,
                  title_max: int = 147) -> dict:
    """Count readable body characters WITH spaces, excluding Markdown and H1.

    We do not silently trim, expand or alter facts to satisfy a limit.
    """
    title_match = re.search(r"(?m)^#\s+(.+?)\s*$", text)
    title = title_match.group(1).strip() if title_match else ""
    body = text[:title_match.start()] + text[title_match.end():] if title_match else text
    visible = _strip_markup(body)
    count = len(visible)
    issues = []
    if not title:
        issues.append("Нет заголовка Markdown H1: первая строка должна быть '# Название'.")
    elif len(title) > title_max:
        issues.append(f"Заголовок: {len(title)} символов, предел {title_max}.")
    if count < minimum:
        issues.append(f"Текст слишком короткий: {count} знаков, минимум {minimum}.")
    if count > maximum:
        issues.append(f"Текст слишком длинный: {count} знаков, максимум {maximum}.")
    return {"title": title, "title_chars": len(title),
            "body_chars": count, "issues": issues, "passed": not issues}
